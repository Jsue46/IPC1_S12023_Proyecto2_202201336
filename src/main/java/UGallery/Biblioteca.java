    private void btnEliminarCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarCategoriaActionPerformed
    String textoSeleccionado = jtxtCategorias.getSelectedText();
    int inicioSeleccionado = jtxtCategorias.getSelectionStart();
    int finSeleccionado = jtxtCategorias.getSelectionEnd();
    int indiceLinea = obtenerIndiceLinea(inicioSeleccionado);

    if (indiceLinea != -1) {
        ListaCategorias.remove(indiceLinea);

        jtxtCategorias.setText("");
        for (Categoria categoria : ListaCategorias) {
            jtxtCategorias.append(categoria.getNombre() + "\n");
        }
    }
    }//GEN-LAST:event_btnEliminarCategoriaActionPerformed

   private int obtenerIndiceLinea(int offset) {
    try {
        int linea = jtxtCategorias.getLineOfOffset(offset);
        return linea;
    } catch (BadLocationException ex) {
        ex.printStackTrace();
    }
    return -1; 
}

    
    
    
    
    
